"""The published full-scale KITTI camera-LiDAR falsification artifact stays consistent.

The artifact is generated by ``tools/publish_kitti_falsification_benchmark.py`` from the
official KITTI raw drive (not part of the repository); these tests need only the
committed files under ``docs/assets``.
"""

from __future__ import annotations

from pathlib import Path

from calibrex.core.io import read_mapping
from calibrex.core.validation import validate_file
from calibrex.evaluation.kitti_falsification_benchmark import (
    KITTI_HEADLINE_METRICS,
    KITTIFalsificationBenchmarkArtifact,
    render_kitti_falsification_markdown,
)

ASSETS = Path("docs/assets")
ARTIFACT = ASSETS / "kitti-camera-lidar-falsification.json"
MARKDOWN = ASSETS / "kitti-camera-lidar-falsification.md"


def _artifact() -> KITTIFalsificationBenchmarkArtifact:
    return KITTIFalsificationBenchmarkArtifact.model_validate(read_mapping(ARTIFACT))


def test_published_artifact_is_schema_valid_with_provenance() -> None:
    assert validate_file(ARTIFACT, kind="kitti-falsification").valid
    artifact = _artifact()
    assert artifact.provenance.git_commit
    assert artifact.dataset_sequence == "2011_09_26_drive_0005_sync"
    assert len(artifact.selected_frame_ids) == 50
    # every camera image and Velodyne scan of the 50 pairs, plus config and calibration
    assert len(artifact.input_artifacts) == 2 * 50 + 3


def test_reference_passes_and_the_declared_known_bad_fails() -> None:
    artifact = _artifact()
    assert artifact.status == "pass"
    trials = {trial.candidate_id: trial for trial in artifact.trials}
    assert trials["dataset_reference"].assessment_status == "pass"
    assert trials["known_bad"].assessment_status == "fail"
    for trial in trials.values():
        assert trial.bundle_valid
        assert all(not Path(item.path).is_absolute() for item in trial.artifacts)
        assert {metric.metric_id for metric in trial.metrics} == set(KITTI_HEADLINE_METRICS)
        assert trial.rules and trial.assessment_reason
    assert all(rule.status == "pass" for rule in trials["dataset_reference"].rules)
    assert any(rule.status == "fail" for rule in trials["known_bad"].rules)


def test_published_markdown_regenerates_from_the_artifact() -> None:
    assert render_kitti_falsification_markdown(_artifact()) == MARKDOWN.read_text(encoding="utf-8")


def test_the_known_bad_is_rejected_only_by_the_reference_comparison() -> None:
    # The published finding: under this protocol no check of the images and scans
    # rejects the declared known-bad; only the comparison with the dataset's own
    # calibration does. A protocol change that alters this must update the page.
    trials = {trial.candidate_id: trial for trial in _artifact().trials}
    failed = [
        check
        for check in trials["known_bad"].evidence_checks
        if check.status == "fail" and check.check != "Decision Boundary"
    ]
    assert failed and all(check.uses_dataset_reference for check in failed)
    assert all(check.status == "pass" for check in trials["dataset_reference"].evidence_checks)


def test_the_images_and_scans_alone_fail_the_known_bad_on_rotation_and_depth() -> None:
    artifact = _artifact()
    decisions = {decision.frame_selection: decision for decision in artifact.data_only}
    assert list(decisions) == ["spread", "first"]
    assert decisions["first"].frame_ids == artifact.selected_frame_ids
    for decision in decisions.values():
        assert len(decision.frame_ids) == 50 and decision.git_commit
        known_bad = {trial.candidate_id: trial for trial in decision.trials}["known_bad"]
        assert known_bad.verdict == "fail"
        # the 5 deg about the camera's yaw axis is a pitch of the rectified pinhole frame
        pitch = {axis.name: axis for axis in known_bad.axes}["pitch"]
        assert pitch.status == "fail" and abs(pitch.candidate_error_deg) > 4.5
        # its 0.25 m along the optical axis, from stereo depth
        depth = known_bad.depth_axis
        assert depth is not None and depth.status == "fail"
        assert 0.2 < depth.candidate_error_m < 0.3
        assert known_bad.depth is not None and known_bad.depth.observable
        for trial in decision.trials:
            assert trial.unchecked_translation_axes == ["x", "y"]


def test_the_reference_sits_at_the_depth_tolerance_so_the_data_alone_do_not_decide() -> None:
    # The published finding: on the spread frames the stereo depth puts the dataset's
    # reference about 5 cm along the optical axis, at the check's tolerance (warn, not
    # fail); on the protocol's first 50 frames its yaw sits at the rotation tolerance.
    # Neither selection passes the reference, so the data-only status is inconclusive.
    artifact = _artifact()
    assert artifact.data_only_status == "inconclusive"
    decisions = {decision.frame_selection: decision for decision in artifact.data_only}
    spread = {trial.candidate_id: trial for trial in decisions["spread"].trials}
    reference = spread["dataset_reference"]
    assert reference.verdict == "warn"
    assert all(axis.status == "pass" for axis in reference.axes)
    depth = reference.depth_axis
    assert depth is not None and depth.status == "warn"
    assert depth.candidate_error_m <= 2 * depth.tolerance_m
    first = {trial.candidate_id: trial for trial in decisions["first"].trials}
    assert first["dataset_reference"].verdict == "warn"
    assert first["dataset_reference"].depth_axis is not None
    assert first["dataset_reference"].depth_axis.status == "pass"
    assert {axis.name: axis.status for axis in first["dataset_reference"].axes}["yaw"] == "warn"
