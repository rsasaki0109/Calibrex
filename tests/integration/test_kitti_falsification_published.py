"""The published full-scale KITTI camera-LiDAR falsification artifact stays consistent.

The artifact is generated by ``tools/publish_kitti_falsification_benchmark.py`` from the
official KITTI raw drive (not part of the repository); these tests need only the
committed files under ``docs/assets``.
"""

from __future__ import annotations

from pathlib import Path

from calibrex.core.io import read_mapping
from calibrex.core.validation import validate_file
from calibrex.evaluation.kitti_falsification_benchmark import (
    KITTI_HEADLINE_METRICS,
    KITTIFalsificationBenchmarkArtifact,
    render_kitti_falsification_markdown,
)

ASSETS = Path("docs/assets")
ARTIFACT = ASSETS / "kitti-camera-lidar-falsification.json"
MARKDOWN = ASSETS / "kitti-camera-lidar-falsification.md"


def _artifact() -> KITTIFalsificationBenchmarkArtifact:
    return KITTIFalsificationBenchmarkArtifact.model_validate(read_mapping(ARTIFACT))


def test_published_artifact_is_schema_valid_with_provenance() -> None:
    assert validate_file(ARTIFACT, kind="kitti-falsification").valid
    artifact = _artifact()
    assert artifact.provenance.git_commit
    assert artifact.dataset_sequence == "2011_09_26_drive_0005_sync"
    assert len(artifact.selected_frame_ids) == 50
    # every camera image and Velodyne scan of the 50 pairs, plus config and calibration
    assert len(artifact.input_artifacts) == 2 * 50 + 3


def test_reference_passes_and_the_declared_known_bad_fails() -> None:
    artifact = _artifact()
    assert artifact.status == "pass"
    trials = {trial.candidate_id: trial for trial in artifact.trials}
    assert trials["dataset_reference"].assessment_status == "pass"
    assert trials["known_bad"].assessment_status == "fail"
    for trial in trials.values():
        assert trial.bundle_valid
        assert all(not Path(item.path).is_absolute() for item in trial.artifacts)
        assert {metric.metric_id for metric in trial.metrics} == set(KITTI_HEADLINE_METRICS)
        assert trial.rules and trial.assessment_reason
    assert all(rule.status == "pass" for rule in trials["dataset_reference"].rules)
    assert any(rule.status == "fail" for rule in trials["known_bad"].rules)


def test_published_markdown_regenerates_from_the_artifact() -> None:
    assert render_kitti_falsification_markdown(_artifact()) == MARKDOWN.read_text(encoding="utf-8")
